import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { readJson } from '../runtime/engine.mjs';

test('packaged hook + real MCP transport + panel complete two turns without manual recording', { timeout: 20000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'shutong-plugin-test-'));
  const main = resolve('plugins/shutong/runtime/main.mjs');
  const mcp = resolve('plugins/shutong/runtime/mcp-server.mjs');
  const env = { ...process.env, SHUTONG_DATA_DIR: directory };
  const hook = input => {
    const result = spawnSync(process.execPath, [main, 'hook'], { env, input: JSON.stringify(input), encoding: 'utf8', timeout: 10000 });
    assert.equal(result.status, 0, result.stderr); return JSON.parse(result.stdout);
  };
  const client = new Client({ name: 'shutong-integration-test', version: '1' });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [mcp], env, stderr: 'pipe' }));
  t.after(async () => {
    await client.close();
    const panel = await readJson(join(directory, 'panel.json'));
    if (panel) await fetch(`${panel.url}/shutdown?token=${panel.token}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' }).catch(() => {});
    await rm(directory, { recursive: true, force: true });
  });
  const call = async (name, args) => {
    const response = await client.callTool({ name, arguments: args });
    assert.ok(!response.isError, response.content[0]?.text);
    return JSON.parse(response.content[0].text);
  };
  const input = { session_id: 'test-session', turn_id: 'turn-one', prompt: '介绍哈希表' };
  const start = hook({ ...input, hook_event_name: 'UserPromptSubmit' });
  const turnKey = start.hookSpecificOutput.additionalContext.match(/SHUTONG_TURN=([a-f0-9]{64})/)[1];
  const concept = { id: 'computer/hash-table', name: '哈希表' };
  const before = await call('context', { turnKey, concepts: [concept], explainIds: [concept.id] });
  assert.equal(before.threshold, 1);
  const evidence = '哈希表通过哈希函数把键映射到桶来存取值。';
  const staged = await call('stage', { turnKey, concepts: [{ ...concept, evidence }] });
  assert.equal(staged.counted, false);
  assert.ok(staged.panelUrl, 'panel must start for integration acceptance');
  hook({ ...input, hook_event_name: 'Stop', last_assistant_message: evidence, stop_hook_active: false });
  const recorded = await call('status', { turnKey });
  assert.equal(recorded.concepts[0].explanationCount, 1);
  assert.equal(recorded.turn.phase, 'recorded');
  const sources=await call('manage',{action:'sources',conceptId:concept.id});
  assert.equal(sources.totalReceipts,1);
  assert.deepEqual(sources.receipts,[{hostId:'codex',sessionId:'test-session',requestId:'turn-one'}]);
  assert.equal((await call('status',{turnKey})).concepts[0].explanationCount,1);
  const next = hook({ ...input, turn_id: 'turn-two', hook_event_name: 'UserPromptSubmit' });
  const secondKey = next.hookSpecificOutput.additionalContext.match(/SHUTONG_TURN=([a-f0-9]{64})/)[1];
  assert.equal((await call('context', { turnKey: secondKey, concepts: [concept] })).concepts[0].mode, 'suppress-basics');
  const url = new URL(staged.panelUrl);
  const pageResponse=await fetch(staged.panelUrl);
  assert.equal(pageResponse.status, 200);
  assert.match(pageResponse.headers.get('Content-Security-Policy'),/img-src 'none'/);
  assert.equal((await fetch(`${url.origin}/state`)).status, 403);
  const update = await fetch(`${url.origin}/threshold?token=${url.searchParams.get('token')}`, {
    method: 'POST', headers: { 'Content-Type': 'application/json', Origin: url.origin }, body: JSON.stringify({ value: 3 }),
  });
  assert.equal(update.status, 200);
  assert.equal((await call('context', { turnKey: secondKey, concepts: [concept] })).concepts[0].mode, 'normal');
  const forbidden = await fetch(`${url.origin}/known?token=${url.searchParams.get('token')}`, {
    method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://example.org' }, body: JSON.stringify({ id: concept.id, known: true }),
  });
  assert.equal(forbidden.status, 403);
  // Session configuration works with the opaque turn key, without exposing a raw session ID.
  await call('config', {scope:'session',turnKey:secondKey,patch:{progressiveDetails:false}});
  const disabled = await call('context', {turnKey:secondKey,concepts:[concept]});
  assert.equal(disabled.presentationPolicy.mode,'normal');
  assert.match(disabled.instruction,/disabled/);
  await call('config', {scope:'session',turnKey:secondKey,clearOverride:true});
  const detailConcept={id:'computer/collision',name:'哈希冲突'};
  await call('context',{turnKey:secondKey,concepts:[detailConcept]});
  const trunk='结论：可以使用哈希表；注意冲突处理。';
  const body='哈希冲突是多个不同的键被映射到了同一个桶。';
  await call('stage',{turnKey:secondKey,concepts:[],presentation:{criticalPoints:['注意冲突处理。'],details:[{id:'collision',title:'冲突处理',body,concepts:[{...detailConcept,evidence:body}]}]}});
  hook({...input,turn_id:'turn-two',hook_event_name:'Stop',last_assistant_message:trunk});
  const query=`token=${url.searchParams.get('token')}&turn=${secondKey}`;
  const opened=await fetch(`${url.origin}/detail?id=collision&${query}`);
  const detailResult=await opened.json();
  assert.equal(detailResult.node.body,body);assert.equal(detailResult.node.bodyHtml,`<p>${body}</p>\n`);
  const panelState=await(await fetch(`${url.origin}/state?${query}`)).json();
  assert.equal(panelState.presentation.trunkHtml,`<p>${trunk}</p>\n`);
  assert.equal(panelState.presentation.details[0].bodyHtml,undefined,'closed details must not be preloaded');
  assert.equal((await call('status',{turnKey:secondKey})).presentation.trunk,trunk);
  assert.equal((await call('context',{turnKey:secondKey,concepts:[detailConcept]})).concepts[0].count,0);
  for(let i=0;i<2;i++)assert.equal((await fetch(`${url.origin}/viewed?${query}`,{method:'POST',headers:{'Content-Type':'application/json',Origin:url.origin},body:JSON.stringify({id:'collision'})})).status,200);
  assert.equal((await call('context',{turnKey:secondKey,concepts:[detailConcept]})).concepts[0].count,1);
  await call('takeaway',{turnKey:secondKey,nodeId:'collision',takeaway:'选择适合负载的冲突处理方式。'});
  assert.equal((await call('status',{turnKey:secondKey})).presentation.takeaways.collision,'选择适合负载的冲突处理方式。');
  const third=hook({...input,turn_id:'turn-three',hook_event_name:'UserPromptSubmit'});
  const thirdKey=third.hookSpecificOutput.additionalContext.match(/SHUTONG_TURN=([a-f0-9]{64})/)[1];
  await call('context',{turnKey:thirdKey,concepts:[]});
  const reviewInput={reviewTrunk:true,trunk:trunk+'不必要的实现细节。'.repeat(80),criticalPoints:['注意冲突处理。'],details:[{id:'collision',title:'冲突处理',body}]};
  const rejected=await call('stage',{turnKey:thirdKey,concepts:[],presentation:reviewInput});
  assert.equal(rejected.prepared,false);assert.equal(rejected.panelUrl,null);assert.equal(rejected.review.status,'revise');
  const approved=await call('stage',{turnKey:thirdKey,concepts:[],presentation:{...reviewInput,trunk}});
  assert.equal(approved.prepared,true);assert.equal(approved.hasDetails,true);assert.equal(approved.review.status,'accepted');
  hook({...input,turn_id:'turn-three',hook_event_name:'Stop',last_assistant_message:trunk});
  assert.equal((await call('status',{turnKey:thirdKey})).turn.lengthReview.status,'accepted');
  const fourth=hook({...input,turn_id:'turn-four',hook_event_name:'UserPromptSubmit'});
  const fourthKey=fourth.hookSpecificOutput.additionalContext.match(/SHUTONG_TURN=([a-f0-9]{64})/)[1];
  const alternatives=await call('context',{turnKey:fourthKey,concepts:[{id:'different/hash',name:'哈希表'}],domain:'algorithms'});
  assert.equal(alternatives.concepts[0].mode,'normal');
  assert.equal(alternatives.concepts[0].candidates[0].id,concept.id);
  const condition='清理旧数据前须验证备份可以恢复。';
  const conditionDraft={trunk:'先安排试点。',reviewTrunk:true,details:[{id:'backup',title:'备份',body:condition,requiredInTrunk:[condition]}]};
  const missing=await call('stage',{turnKey:fourthKey,concepts:[],presentation:conditionDraft});
  assert.equal(missing.prepared,false);assert.equal(missing.panelUrl,null);
  assert.equal(missing.review.status,'missing-critical-points');assert.deepEqual(missing.review.missingCriticalPoints,[condition]);
  assert.equal((await call('stage',{turnKey:fourthKey,concepts:[{...concept,evidence:''}],presentation:{...conditionDraft,trunk:condition}})).prepared,true);
  hook({...input,turn_id:'turn-four',hook_event_name:'Stop',last_assistant_message:condition});
  assert.equal((await call('status',{turnKey:fourthKey})).presentation.trunk,condition);
  await call('config',{patch:{enabled:false}});
  assert.deepEqual(hook({...input,turn_id:'disabled',hook_event_name:'UserPromptSubmit'}),{});
});
